/** Look up a directory entry by email (case-insensitive) or by full name. */
export function findDirectoryProfile(
  emailOrName: string | undefined | null,
): SignatureProfile | undefined {
  if (!emailOrName) return undefined;
  const key = emailOrName.trim().toLowerCase();
  return SIGNATURE_DIRECTORY.find(
    (p) => p.email.toLowerCase() === key || p.name.toLowerCase() === key,
  );
}

/** Serialize a directory entry back into the repo snippet format. */
export function directorySnippet(p: SignatureProfile): string {
  const lines = [
    `  name: ${JSON.stringify(p.name)},`,
    `  position: ${JSON.stringify(p.position)},`,
    p.width ? `  width: ${JSON.stringify(p.width)},` : null,
    `  image: ${JSON.stringify(p.image)},`,
    `  website: ${JSON.stringify(p.website)},`,
    `  email: ${JSON.stringify(p.email)},`,
    p.phone ? `  phone: ${JSON.stringify(p.phone)},` : null,
    p.phoneOpen ? `  phoneOpen: ${JSON.stringify(p.phoneOpen)},` : null,
  ].filter(Boolean);
  return `{\n${lines.join("\n")}\n}`;
}
